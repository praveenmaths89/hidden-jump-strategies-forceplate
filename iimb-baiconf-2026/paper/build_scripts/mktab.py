# Lays out the R-generated tables for the Overleaf project (IIMB MR house style).
# Every number comes from the R pipeline: the LaTeX bodies in package/output/paper_tables_latex/
# or, where more precision is needed for consistent rounding, the CSVs in
# package/output/main_lowest_com/tables/. Only layout, labels, captions and notes are added here.
# Style: booktabs rules, no vertical rules, units in headers, siunitx S columns (decimal alignment),
# CIs as [a, b], short caption above, notes below (threeparttable), floats [!htbp].
import re, os, csv
P = '/workspace/iimb-baiconf-2026/package/output/'
T = P + 'paper_tables_latex/'; C = P + 'main_lowest_com/tables/'
O = '/workspace/iimb-baiconf-2026/overleaf/tables/'
def rows(f):
    s = open(T + f).read()
    body = re.split(r'(?<!c)\\midrule', s, maxsplit=1)[1].split('\\bottomrule')[0].strip()
    out = []
    for line in body.split('\\\\'):
        line = line.strip()
        if line: out.append([c.strip().replace('$-$', '-') for c in line.split('&')])
    return out
def rcsv(f): return list(csv.DictReader(open(C + f)))
def f(x, d): return f'{float(x):.{d}f}'
def ci(lo, hi): return '{[' + lo + ', ' + hi + ']}'
def paren(s):  # "0.89 (0.70--1.06)" -> ("0.89", "0.70", "1.06")
    m = re.fullmatch(r'(-?[\d.]+) \((-?[\d.]+)--(-?[\d.]+)\)', s); return m.groups()
def write(src, label, caption, size, colspec, head, body, note):
    txt = ('% Generated by build2/mktab.py from the R pipeline output (' + src + '); layout only.\n'
           '\\begin{table}[!htbp]\n\\centering\n\\begin{threeparttable}\n\\caption{' + caption + '}\n\\label{' + label + '}\n'
           + size + '\n\\begin{tabular}{' + colspec + '}\n\\toprule\n' + head + '\n\\midrule\n' + body + '\n\\bottomrule\n\\end{tabular}\n'
           '\\begin{tablenotes}[flushleft]\\footnotesize\n\\item \\textit{Note.} ' + note + '\n\\end{tablenotes}\n\\end{threeparttable}\n\\end{table}\n')
    open(O + src, 'w').write(txt)
for old in os.listdir(O): os.remove(O + old)
