TITLE = "Revealing hidden jump strategies beyond conventional force-plate metrics"
SHORT = "Hidden strategies in jump curves"
ABSTRACT = ("Force-plate software summarises each countermovement jump (CMJ) with a few vendor metrics, and athletes with "
 "similar values are treated as equivalent. We tested this assumption on 805 routinely collected CMJ trials from 212 male "
 "footballers in India. Principal component analysis of body-weight-normalised take-off and landing force\u2013time curves "
 "retained four components (74.8% of variance), located almost entirely in the landing phase. Trials matched on jump height "
 "or relative peak force varied almost as much as the full sample, and vendor metrics, age and body mass explained only "
 "2.7\u201313.1% of each component. Routine force-plate data therefore hold unused information for athlete-monitoring decisions.")
KEYWORDS = ["Countermovement jump", "Principal component analysis", "Force\u2013time curve", "Force plates",
            "Athlete monitoring", "Landing", "Sports analytics", "Football"]
SUMMARY = [
 "High-performance centres invest in force plates and test athletes routinely, yet decisions about those athletes usually rest "
 "on a handful of vendor-computed numbers such as jump height and peak force. Athletes with similar numbers are then treated as "
 "if they had jumped in the same way. We ask whether this holds, and how much recorded information those numbers leave unused.",
 "We analysed 805 countermovement jumps from 212 male football players tested during routine monitoring at a high-performance "
 "centre in Thane, Mumbai. Each force\u2013time curve was normalised to body "
 "weight, take-off and landing phases were each time-normalised and joined, and principal component analysis was used to "
 "find the main patterns of variation. We then compared the spread of curve shapes among jumps matched on jump height or on "
 "relative peak force with the spread in the whole sample, and measured how much of each pattern four vendor metrics, age and "
 "body mass explain.",
 "Four components explained 74.8% of curve variance, and all four lay almost entirely in the landing phase; the first described "
 "how quickly the athlete arrested the fall. Jumps matched on jump height were scarcely more alike in shape than jumps in "
 "general, and matching on relative peak force had no effect. The conventional metrics, age and body mass explained only "
 "2.7\u201313.1% of each component (0.3\u201311.8% out of sample). Between-athlete differences accounted for 10.0\u201329.6% of "
 "component variance, so much of the variation was trial-specific. With a fixed 1-s landing window, a take-off component "
 "appeared that the metrics largely explained.",
 "For managers of sports-science programmes, the landing is recorded in every jump at no extra cost; simple landing descriptors "
 "could be added to routine reports, and decisions should rest on several trials rather than a single landing. "
 "Dimensionality reduction can extract additional, decision-relevant information from data that organisations already collect."]
